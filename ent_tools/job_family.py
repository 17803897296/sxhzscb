# 展平并按「长词优先」排序：先比长度（长词更具体，如「信息安全」优先于「安全」），
# 等长时按 FAMILIES 的书写顺序（前面列的族优先，如「教师」优先于「化学」）。
_KW = []
for _fam, _words in FAMILIES.items():
    for _i, _w in enumerate(_words):
        _KW.append((_norm(_w), _fam, -len(_norm(_w)), len(_KW)))
_KW.sort(key=lambda x: (x[2], x[3]))

# 给 JS 用的有序视图：[[关键词, 族], ...]，顺序即匹配优先级。
JS_TABLE = [[w, f] for w, f, _, _ in _KW]

_CACHE = {}


def family_of(name):
    """岗位名 → 职能族；认不出来返回 ""（"" 表示「不表态」，不是「无职能」）。"""
    key = _norm(name)
    if not key:
        return ""
    hit = _CACHE.get(key)
    if hit is not None:
        return hit
    fam = ""
    for w, f, _, _ in _KW:
        if w in key:
            fam = f
            break
    _CACHE[key] = fam
    return fam


def cross_function(title, intent):
    """两者是否**明确**属于不同职能。任一侧认不出来就返回 False（不表态）。"""
    a = family_of(intent)
    if not a:
        return False
    b = family_of(title)
    return bool(b) and a != b


