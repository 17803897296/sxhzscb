# 架构是「先搜后喂」：证据先搜出来注入提示词，模型只能从证据里提岗位名，
# 代码再落地校验——三道闸保证「岗位名是真的」：
#   1. 提示词立规矩：岗位叫法只能取自证据里的写法，why 必须引用来源；
#   2. 代码落地校验（_grounded）：输出岗位名在证据原文里找不到就丢；
#   3. 类别标签拦截（_bad_title）：「计算机类岗位」「信息技术」这类公告标签
#      不当岗位名提给学生。
# 踩过的两条弯路（都实测过）：
#   · 智谱 /web_search 两步走：可用，但 key 是视觉那把的试用额度，十几次打空；
#   · chat 内嵌 deepseek_web_search 工具：**只有 deepseek-flash 支持**且
#     **调用与否模型自主决定**（tool_choice 强制不支持，实测 400），连发两次
#     都可能懒得搜——不可依赖。
# 独立 Search 接口每次请求都必然返回结果（5 元/千次），证据落盘缓存 6 小时
# （同一专业几小时内没必要重复计费搜索）。证据为空/接口失败 → 降级纯模型
# 口径 → 规则兜底，演示可离线的边界不变。

_SEARCH_URL = "https://api.deepseek.com/v1/tools/search"


def _ds_search(query, key, count=8, timeout=30):
    """调 DeepSeek 独立 Search API，返回 [{title, summary, site, date}]；失败 []。

    summary（600~800 字的长摘要）比 snippet（100~200 字展示用）更适合喂模型，
    这里截 300 字——证据块要整个进提示词，太大模型会抄偏。
    """
    body = json.dumps({"query": query[:128], "count": count,
                       "need_content": False}).encode("utf-8")
    req = urllib.request.Request(
        _SEARCH_URL, data=body,
        headers={"Content-Type": "application/json",
                 "Authorization": "Bearer " + key})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            out = json.loads(r.read().decode("utf-8"))
    except Exception as e:
        print("[job_recommend] 联网搜索失败：%s" % e, file=sys.stderr)
        return []
    res = []
    for x in (out.get("results") or []):
        res.append({"title": str(x.get("title") or ""),
                    "summary": str(x.get("summary") or "")[:300],
                    "site": str(x.get("site_name") or ""),
                    "date": str(x.get("date") or "")[:10]})
    return res


def web_evidence(major, key):
    """两路搜索拼证据：「本专业校招岗位」+「所属大类校招岗位」，去重截 16 条。

    证据落盘缓存 6 小时：一次池构建会逐层调 llm_pool（每层 2 次搜索），
    同一专业的证据几小时内没必要重复计费。
    """
    cat = major_category(major)
    cache_key = hashlib.md5(("%s|%s" % (major, cat)).encode("utf-8")).hexdigest()[:16]
    with _LOCK:
        cache = _load_search_cache()
        hit = cache.get(cache_key)
        if hit and time.time() - hit.get("ts", 0) < SEARCH_TTL:
            return hit.get("ev") or []
    ev = _ds_search("%s 应届生 校园招聘 岗位" % (major or ""), key)
    if cat and cat != UNKNOWN_CAT:
        ev += _ds_search("%s 校招 热门岗位 应届生" % cat, key)
    out, seen = [], set()
    for x in ev:
        t = x["title"]
        if t and t not in seen:
            seen.add(t)
            out.append(x)
    out = out[:16]
    if out:
        with _LOCK:
            cache = _load_search_cache()
            cache[cache_key] = {"ts": time.time(), "ev": out}
            _save_search_cache(cache)
    return out


SEARCH_CACHE_FILE = os.path.join(DATA, "web_evidence_cache.json")
SEARCH_TTL = 6 * 3600


def _load_search_cache():
    try:
        with open(SEARCH_CACHE_FILE, encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return {}


def _save_search_cache(cache):
    try:
        os.makedirs(DATA, exist_ok=True)
        fresh = {k: v for k, v in cache.items()
                 if time.time() - v.get("ts", 0) < SEARCH_TTL}
        with open(SEARCH_CACHE_FILE, "w", encoding="utf-8") as f:
            json.dump(fresh, f, ensure_ascii=False)
    except Exception:
        pass


# ── 跨专业拦截（代码级，2026-11-17 用户反馈：仍有非本专业岗位混入）──────
# 提示词禁令挡不全，代码再拦一道：岗位名必须命中该生学科大类的方向词
# （biz_recheck 的专业词表），否则剔除。
#   · tier 0-2（切合专业 / 相邻方向）：只认方向词命中；
#   · tier 3（通用职能）：方向词命中或通用职能词都放行；
#   · tier 4（不限专业 / 教培）：不拦——这一层本来就是跨专业出口。
# 学生专业识别不出领域（fields 为空）时不拦，宁漏勿错杀。
_GENERIC_MARK = re.compile(
    r"质量|生产管理|生产计划|生产跟单|采购|供应商|仓储|物流|供应链|"
    r"技术销售|售前|售后|技术支持|项目助理|客服|EHS|安全工程师|计划员|测试")


_NOT_MAJOR_MARK = re.compile(
    r"美工|平面设计|平面|插画|原画|UI设计|视频剪辑|剪辑师|主播|配音|"
    r"翻译|导游|护士|护理|化妆|造型师|摄影师")

# 邻专业核心岗拦截（2026-11-18 用户实测：材料专业第 3 层被混进化学化工核心岗）。
# 根因：student_domain 把「材料 / 化学 / 化工」并进同一个 field（化学化工材料），
# kw 三家的词全在里面，_major_ok 光看 kw 就分不清「材料的相邻岗」和「化工的核心岗」。
# tier2 的 prompt 明明举的是「化工专业→化工设备/中试放大」，闸门却把同一批岗放给了
# 材料专业——等于把隔壁专业的核心岗当放宽推给学生，投了必被筛。
# 全量大类审计（2026-11-18）发现同构漏网三处，一并纳入：
#   · 冶金 / 无机非等「材料侧」专业和材料共用化工池，同样被塞化工设备/中试/催化；
#   · 通信 / 微电子（弱电）被塞电机设计 / 配电设计 / 电梯暖通（电气强电核心岗）；
#   · 动物医学 / 畜牧 / 水产（养殖侧）被塞农艺师 / 育种 / 植保（种植核心岗）。
# 每条形如 (命中本专业的词, 自身豁免词, 禁入的邻专业核心岗)。词表只收**别家核心岗**，
# 本专业能投的通用岗（金相、材料检测、理化检验）不动。
_NEIGHBOR_CORE = [
    (("材料", "冶金", "无机非金属", "复合材料"), ("化工", "化学工程"),
     re.compile(r"化工工艺|化工设备|化工设计|中试/?放大|催化研发|危化品")),
    (("通信", "电子", "微电子", "光电", "仪器", "测控"), ("电气",),
     re.compile(r"电机设计|配电设计|电梯/暖通|电气设计")),
    (("动物", "兽医", "畜牧", "水产", "养殖"), ("农学", "园艺", "植保", "植物保护"),
     re.compile(r"农艺师|育种技术员|植保技术员|种子检验|测土配方")),
    # 对称：种植侧（农学/园艺）不得拿兽医 / 饲料 / 养殖这些养殖核心岗
    (("农学", "作物", "园艺", "植保", "植物保护", "茶学", "林学", "园林", "种子"),
     ("动物", "兽医", "畜牧", "水产", "养殖"),
     re.compile(r"兽医|动物医|饲料|养殖技术员|畜牧|水产|宠物医")),
]


def _neighbor_core_blocked(title, major):
    """学生专业的邻专业核心岗不得混入（材料/冶金↔化工、弱电↔强电、养殖↔种植）。

    按「具体专业 → 不许出现的邻专业核心岗」精确拦截；学生自己就是该专业时
    （如化工学生看化工设备）由豁免词放行。返回是否被拦。
    """
    m = str(major or "")
    t = str(title or "")
    for own_words, exempt_words, pat in _NEIGHBOR_CORE:
        if not any(w in m for w in own_words):
            continue
        if any(x in m for x in exempt_words):
            continue
        if pat.search(t):
            return True
    return False


def _major_ok(title, major, tier):
    if tier is None or tier >= 4:
        return True
    t = title or ""
    # 邻专业核心岗：先于 kw 判定，避免合并大类词表把它放行
    if _neighbor_core_blocked(t, major):
        return False
    # 先挡「名字里带领域词、但干的明显是别的活」的岗位：
    # 物流域有「电商」，但「电商美工」是设计岗不是物流岗。
    if _NOT_MAJOR_MARK.search(t):
        return False
    try:
        kw, fields = biz_recheck.student_domain("", major or "")
    except Exception:
        return True
    if not fields or not kw:
        return True
    if any(w in t for w in kw):
        return True
    return tier >= 3 and bool(_GENERIC_MARK.search(t))


def _evidence_text(evidence):
    return " ".join((x["title"] or "") + " " + (x["summary"] or "")
                    for x in evidence)


def _grounded(title, evidence_text):
    """落地校验：岗位叫法必须真的出现在搜索证据里。

    先查清理后的全名，查不到再剥掉职级后缀取核心词查——「食品研发工程师」
    证据里常写成「食品研发」，全名查不中但核心查得中。核心词剥空的
    （管培生/专员）全名必须出现，避免「专员」这种字到处都在等于没校验。

    落地≠合格：公告里的类别标签（「计算机类岗位」「信息技术」「校园招聘」）
    能落地但不是能投的岗位名，_bad_title 一并拦掉。
    """
    t = _clean_title(title)
    if not t or _bad_title(t):
        return False
    if t in evidence_text:
        return True
    core = re.sub(r"(岗|专员|工程师|管培生|经理|助理|分析师|技术员|管理员|员|师)$",
                  "", t)
    return len(core) >= 2 and core in evidence_text


# 公告里的类别标签 / 招聘活动名：能从证据里落地，但不是学生能投的具体岗位。
_BAD_TITLE = re.compile(
    r"(类岗位|相关岗位|类人才|校园招聘|宣讲会|双选会|招聘会|职位|投递|速来|"
    r"招聘公告|岗位汇总|就业信息|人才招聘)$|^(信息技术|其他|其它|综合类)$")


# 企业专属项目名（管培 / 训练营计划名）：能从证据里落地，但不是职能岗位名，
# 学生也对不上——「新锐之星」是某家的管培项目，不是可以投的岗。
_PROJECT_MARK = re.compile(
    r"(之星|新星|新锐|青苗|菁英|英才|训练营|特训营|加速营|研习营|"
    r"领航|启航|扬帆|远航|雏鹰|飞鹰|星火|灯塔|工匠|精英汇)")

# 两个字的「职能域词」不是岗位名：模型把公告里的小标题（「质量」「生产」）
# 当岗名抄出来，学生看不到要投什么。两字但**确实是职业名**的（会计/审计/
# 法务/出纳/美工/编辑…）必须放行，否则经管类学生的对口岗会被一起挡掉。
_SHORT_DOMAIN = {
    "质量", "生产", "研发", "工艺", "制造", "技术", "销售", "市场", "运营",
    "采购", "物流", "仓储", "计划", "行政", "人事", "财务", "测试", "检验",
    "供应链", "外贸", "商务", "工程",
}
# 两字但确实是职业名的：放行。
_SHORT_OK = {
    "会计", "审计", "法务", "出纳", "美工", "编辑", "设计", "翻译", "导游",
    "护士", "律师", "医生", "教师", "客服", "厨师", "司机",
}


def _bad_title(t):
    s = str(t or "").strip()
    if len(s) <= 2 and s in _SHORT_DOMAIN and s not in _SHORT_OK:
        return True
    return bool(_BAD_TITLE.search(t) or _PROJECT_MARK.search(t))


LLM_PROMPT_WEB = """你是双选会会前规划助手，帮学生想清楚「校园招聘里一般可以投哪些岗位」。

学生专业：{major}
所属学科大类：{category}
【实习】{internships}
【竞赛】{competitions}
【论文 / 科研】{papers}
【技能】{skills}

本轮推荐口径（重要）：{tier_rule}

历次已经展示过、本轮尽量不要重复的岗位：{shown}

下面是刚刚联网搜索到的真实校招信息（标题 + 摘要 + 来源网站），共 {n_ev} 条：

{evidence}

请从上面的搜索结果里提取适合该学生的岗位名称，硬性要求：
1. **岗位名给「职能方向级」的通用叫法**，让学生一眼能对上自己的专业方向：
   企业专属项目名（「新锐之星」「青苗计划」这类管培 / 训练营项目名）、企业名、
   地域、年份、批次一律去掉，只保留职能主体——
   「京东2026新锐之星（物流方向）」→「物流管培生」，不保留「新锐之星」这种项目名。
   可以去掉企业定制括号（「嵌入式软件工程师（心电贴片）」→「嵌入式软件工程师」）；
   归一后的职能词必须真的来自搜索结果（代码会做落地校验，证据里没有的职能词会被丢掉）。
   「运营优化」「系统方案」这类职能描述不算岗位名，不要输出；
   「计算机类岗位」「信息技术」这种公告里的**类别标签**也不是岗位名，
   不要输出——宁可不要这个来源的岗，也不要把标签当岗位提给学生。
2. **why 必须引用证据**：说明是从哪条搜索信息里看到的（引来源网站或公告
   标题的关键词），再加一句为什么适合这个学生。
3. 与学生专业、学科大类**对不上**的岗位一律不要提——搜索结果里有不代表适合：
   物流专业的结果里出现「平面设计」「行政专员」「电商美工」就不要提；
   开发 / 算法 / 设计这类技术岗不是本大类方向时也不要提。宁少勿滥。
4. 档位必须是应届投得进的：不要「主管 / 资深 / 高级 / 组长 / 总监 / 专家」；
   「经理」只保留校招真正常见的三种（客户经理、产品经理、业务经理）。
5. 目标 12 个左右、互不重复、避开已展示过的岗位；对口的不足就少给，不硬凑。
6. 严格输出 JSON：{{"candidates":[{{"title":"岗位名","why":"一句话依据（含来源）"}}]}}

"""


def _llm_chat_json(base_url, key, model, prompt):
    """一次对话调用，解析出 candidates 清单（清理去重后）；失败返回 None。"""
    payload = {"model": model,
               "messages": [{"role": "user", "content": prompt}],
               "temperature": 0.3, "stream": False}
    req = urllib.request.Request(
        base_url.rstrip("/") + "/chat/completions",
        data=json.dumps(payload, ensure_ascii=False).encode("utf-8"),
        headers={"Content-Type": "application/json", "Authorization": "Bearer " + key})
    with urllib.request.urlopen(req, timeout=120) as r:
        raw = json.loads(r.read().decode("utf-8"))
    msg = raw["choices"][0]["message"]
    data = _parse_json(msg.get("content"))
    out, seen = [], set()
    for c in (data.get("candidates") or []):
        if not (isinstance(c, dict) and c.get("title")):
            continue
        t = _clean_title(c["title"])
        if not t or t in seen:
            continue
        seen.add(t)
        out.append({"title": t, "why": str(c.get("why", ""))})
    return out or None


def llm_pool(major, cats, tier, accept, key, base_url, model, shown):
    """返回 (池子, 来源) —— 来源 'web'=联网落地 / 'plain'=纯模型口径；失败 None。

    主路径：独立 Search API 先搜真实校招证据 → 注入提示词 → 模型只从证据
    里提岗位名 → 代码落地校验（_grounded）——造词在这一步被拦死。
    搜索失败 / 输出无一落地 → 降级纯模型口径（v15）→ 规则兜底。
    """
    evidence = web_evidence(major, key)
    if evidence:
        prompt = LLM_PROMPT_WEB.format(
            major=major or "未填写",
            category=major_category(major),
            internships="；".join(cats["internships"]) or "无",
            competitions="；".join(cats["competitions"]) or "无",
            papers="；".join(cats["papers"]) or "无",
            skills="、".join(cats["skills"]) or "无",
            tier_rule=TIER_RULES[tier],
            shown="、".join(shown) or "无",
            n_ev=len(evidence),
            evidence="\n".join(
                "- [%s] %s：%s" % (x["site"] or "来源", x["title"], x["summary"])
                for x in evidence))
        try:
            items = _llm_chat_json(base_url, key, model, prompt)
            if items:
                ev_text = _evidence_text(evidence)
                n0 = len(items)
                items = [c for c in items if _grounded(c["title"], ev_text)]
                n_g = n0 - len(items)
                n_m = 0
                if items:
                    kept = [c for c in items if _major_ok(c["title"], major, tier)]
                    n_m = len(items) - len(kept)
                    items = kept
                if items:
                    if n_g:
                        print("[job_recommend] 联网模式拦掉 %d 个不在搜索结果里的岗位名"
                              % n_g, file=sys.stderr)
                    if n_m:
                        print("[job_recommend] 联网模式拦掉 %d 个与专业方向对不上的岗位"
                              % n_m, file=sys.stderr)
                    return items, "web"
                print("[job_recommend] 联网输出无一落地，降级纯模型口径",
                      file=sys.stderr)
        except Exception as e:
            print("[job_recommend] 联网调用失败，降级纯模型口径：%s" % e,
                  file=sys.stderr)
    else:
        print("[job_recommend] 无搜索结果（断网 / 计费配额用尽），降级纯模型口径",
              file=sys.stderr)

    # 降级路径：v15 纯模型口径（模型自己想，不带证据）。
    prompt = LLM_PROMPT.format(
        major=major or "未填写",
        category=major_category(major),
        internships="；".join(cats["internships"]) or "无",
        competitions="；".join(cats["competitions"]) or "无",
        papers="；".join(cats["papers"]) or "无",
        skills="、".join(cats["skills"]) or "无",
        tier_rule=TIER_RULES[tier],
        shown="、".join(shown) or "无")
    try:
        items = _llm_chat_json(base_url, key, model, prompt)
        if items:
            n0 = len(items)
            items = [c for c in items if _major_ok(c["title"], major, tier)]
            if n0 - len(items):
                print("[job_recommend] 纯模型口径拦掉 %d 个与专业方向对不上的岗位"
                      % (n0 - len(items)), file=sys.stderr)
        return (items, "plain") if items else None
    except Exception as e:
        print("[job_recommend] 模型调用失败，回退规则：%s" % e, file=sys.stderr)
        return None


def get_pool(major, cats, tier, accept, cfg, use_llm=True):
    """每个 (专业, 三类经历, 层级, 模型) 一个固定池子，缓存到磁盘，避免换一批时反复调模型。

    层的先后顺序是「由紧到松」，同一批岗本来会在好几层都成立，所以高层必须知道
    低层已经给过什么，否则模型的答案会层层重复、去重后高层所剩无几（实测「相邻
    有门槛」那一层只剩 3 个）。这里把低层池子的岗位名作为 shown 一起喂给模型。
    低层池子本身是确定性的（同样的输入 → 同样的缓存），所以这不会破坏缓存键。
    """
    api_key = os.environ.get("DEEPSEEK_API_KEY") or cfg.get("DEEPSEEK_API_KEY", "")
    base_url = (os.environ.get("DEEPSEEK_BASE_URL") or cfg.get("DEEPSEEK_BASE_URL")
                or "https://api.deepseek.com")
    model = os.environ.get("DEEPSEEK_MODEL") or cfg.get("DEEPSEEK_MODEL") or "deepseek-chat"

    prev = []
    for i in range(max(0, int(tier))):
        p, _ = get_pool(major, cats, i, accept, cfg, use_llm)
        prev.extend(c["title"] for c in p)

    key = _pool_key(major, cats, tier, accept, model, bool(use_llm and api_key),
                    prev=prev)
    with _LOCK:
        pools = _load_pools()
        hit = pools.get(key)
        if isinstance(hit, dict) and hit.get("items"):
            return hit["items"], hit.get("mode", "rules")

    items, mode = None, None
    if api_key and use_llm:
        res = llm_pool(major, cats, tier, accept, api_key, base_url, model, prev)
        if res:
            items, mode = res[0], ("llm-web" if res[1] == "web" else "llm")
            # 模型可能仍然给出低层已经展示过的岗（prompt 里写了「尽量不重复」，
            # 不是硬保证）。这里按层序剔一遍，保证每一层的池子内部就是干净的。
            _p = set(prev)
            items = [c for c in items if c["title"] not in _p] or None
    mode = mode if items else "rules"
    if not items:
        items = rule_pool(major, cats, tier, accept)
    elif len(items) < MIN_FILL:
        # 模型常只给 6~8 个：用同层规则池补到 10 个，保证「换一批」本层还有货。
        # 只设下限、不设上限——这一层有多少就给多少，凑够 10 就停，不多塞。
        # 补的时候同样跳过低层已给过的岗，否则补出来的还是上一层的货。
        seen = {c["title"] for c in items} | set(prev)
        for c in rule_pool(major, cats, tier, accept):
            if c["title"] not in seen:
                items.append(c)
                seen.add(c["title"])
            if len(items) >= MIN_FILL:
                break
    if tier == 4 and accept:
        # 保底：这一层是「放宽到不限专业」，教培岗位必须真的出现在最前面，
        # 不能全靠模型自觉（实测模型有时只给市场/人事这类泛岗位）。
        #
        # 同时把模型混进来的「本专业岗」剔掉：实测 tier3 会补出「食品研发工程师 /
        # 食品质量工程师」，排在校区运营管培生之后 —— 万金油层里混进最专的岗，
        # 顺序就成了「专业 → 大类 → 万金油 → 又回到专业」，与「最后万金油」相反。
        seed = [{"title": t, "why": "不限专业岗位；你已选择愿意考虑教培类企业",
                 } for t in NO_MAJOR_JOBS[:6]]
        seed_titles = {s["title"] for s in seed}
        items = seed + [c for c in items
                        if c["title"] not in seed_titles
                        and not _major_ish(c["title"], major)]
    with _LOCK:
        pools = _load_pools()
        pools[key] = {"tier": tier, "mode": mode, "items": items,
                      "model": model, "prompt_ver": PROMPT_VER,
                      "ts": time.strftime("%Y-%m-%d %H:%M:%S"),
                      "_cg": cache_guard.stamp("job_recommend_pool", model=model)}
        _save_pools(pools)
    return items, mode


NO_MAJOR_MSG = ("还没拿到你的专业，我不给推荐。岗位对不对口只能按专业判——"
                "先回上一步把专业填上（学校、年级可以不填），我再给岗位。")


def recommend(major, internships=None, competitions=None, papers=None,
              skills=None, use_llm=True, shown=None, tier=0,
              accept_no_major=False, experiences=None, allow_relax=False):
    """返回一批 6 个岗位。

    **只在当前层内换**（2026-11-17 修）：以前本层空了会自动升到下一层，而第 4 层
    （通用职能）和第 5 层（不限专业）是跨专业池，学生点两三次「换一批」就被灌进
    质量/生产/测试/客服/管培一堆岗，还和 tier0 的对口岗长得一模一样。现在升层
    必须由学生显式点「放宽一档」（allow_relax=True），且跨专业层在前端带角标。

    major 为空直接拒绝：`_major_ok` 对「识别不出领域」原来是放行的（宁漏勿错杀），
    专业空着等于闸门不存在——实测同一个 tier1，空专业给「销售/行政/人事/生产技术员」，
    材料给「研发/工艺/化验/分析测试」。所以在这一层就断掉，不再退化成泛岗。

    shown：采集端历次展示过的岗位名（全局累积），跨层也不重复。
    experiences：兼容旧调用，内容并入实习。
    """
    major = str(major or "").strip()
    if not major:
        return {"ok": False, "need_major": True, "error": NO_MAJOR_MSG,
                "mode": "blocked", "candidates": [], "tier": 0,
                "tier_label": "", "notice": NO_MAJOR_MSG,
                "has_next": False, "cross_major": False, "relaxed": False,
                "accept_no_major": bool(accept_no_major)}

    cats = {
        "internships": _as_list(list(internships or []) + list(experiences or [])),
        "competitions": _as_list(competitions),
        "papers": _as_list(papers),
        "skills": _as_list(skills),
    }
    shown = _as_list(shown)
    # 第 4 层（通用职能）也要学生点头才放开：它以前由 accept_no_major 之外的
    # 逻辑无条件参与，等于「愿意考虑教培」这个答案只管第 5 层、不管第 4 层。
    max_tier = 4 if bool(accept_no_major) else 2
    try:
        start = max(0, min(max_tier, int(tier)))
    except Exception:
        start = 0
    end = max_tier if allow_relax else start

    cfg = _load_env()
    mode = "rules"
    for t in range(start, end + 1):
        pool, mode = get_pool(major, cats, t, accept_no_major, cfg, use_llm)
        fresh = [c for c in pool if c["title"] not in shown]
        if fresh:
            batch = fresh[:6]
            left = len(fresh) - len(batch)
            has_next = t < max_tier
            if has_next:
                note = ("第 %d 层「%s」：本层还剩 %d 个；换一批只在本层换，"
                        "想看更宽的岗位需要你点「放宽一档」。"
                        % (t + 1, TIER_LABELS[t], left))
            else:
                note = "已是最宽口径「%s」。本层还剩 %d 个。" % (TIER_LABELS[t], left)
            return {"ok": True, "mode": mode, "candidates": batch,
                    "tier": t, "tier_label": TIER_LABELS[t],
                    "relaxed": t > start, "pool_left": left, "has_next": has_next,
                    "cross_major": t >= 3,
                    "accept_no_major": bool(accept_no_major), "notice": note}
    # 这一层看完了：不偷偷升层，如实说，并告诉学生还有没有更宽的
    has_next = start < max_tier
    return {"ok": True, "mode": mode, "candidates": [],
            "tier": start, "tier_label": TIER_LABELS[start],
            "relaxed": False, "pool_left": 0, "has_next": has_next,
            "cross_major": start >= 3,
            "accept_no_major": bool(accept_no_major),
            "notice": ("这一层能给的岗位都看过了。"
                       + ("想看更宽的岗位，点下面「放宽一档」。" if has_next
                          else "已经是最宽口径，可以手写想投的岗位。"))}


class Handler(BaseHTTPRequestHandler):
    def do_POST(self):
        if not self.path.startswith("/api/fair/recommend-jobs"):
            self.send_error(404)
            return
        n = int(self.headers.get("Content-Length", 0))
        body = json.loads(self.rfile.read(n) or b"{}")
        out = recommend(
            body.get("major", ""),
            internships=body.get("internships") or [],
            competitions=body.get("competitions") or [],
            papers=body.get("papers") or [],
            skills=body.get("skills") or [],
            use_llm=body.get("use_llm", True),
            shown=body.get("shown") or body.get("exclude") or [],
            tier=body.get("tier", 0),
            accept_no_major=bool(body.get("accept_no_major")),
            allow_relax=bool(body.get("allow_relax")),
            experiences=body.get("experiences") or [])
        raw = json.dumps(out, ensure_ascii=False).encode("utf-8")
        self.send_response(200)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Content-Length", str(len(raw)))
        self.end_headers()
        self.wfile.write(raw)

    def do_OPTIONS(self):
        self.send_response(204)
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Headers", "Content-Type")
        self.end_headers()

    def log_message(self, *a):
        pass


