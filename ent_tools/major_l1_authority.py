def authority_for(major):
    """按子串匹配返回对口 L1 列表；命中具体词优先（按 key 长度降序）。

    只做「词根 in 用户输入」单向匹配：用户输入「生物医学工程」会命中「生物医学」
    词根，但用户输入「生物」不会被「生物医学」词根误命中（后者是 MAJOR_BASE 的
    既有专业，不该被本表的医疗器械岗覆盖）。

    返回 (jobs, matched_key)；无命中返回 (None, None)。
    """
    m = major or ""
    if not m:
        return None, None
    hits = []
    for key, jobs in AUTHORITY.items():
        if key in m:
            hits.append((len(key), key, jobs))
    if not hits:
        return None, None
    hits.sort(key=lambda x: x[0], reverse=True)
    return list(hits[0][2]), hits[0][1]
