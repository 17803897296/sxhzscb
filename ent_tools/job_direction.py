"""岗位方向判定：把「工艺工程师」这种不带方向的岗名，按**主营业务**推定方向。

为什么需要这一层
----------------
判「这家单位对口不对口」时最怕两种错：

  ① 通用岗名一刀切放行 —— 「工艺工程师」在化工厂、汽车零部件厂、家纺厂、
     施工企业里都叫这个名，但化工厂做的是反应与分离，汽车厂做的是注塑与涂装。
     25 家企业都有这个岗名就 25 家全判 yes，等于没筛。
  ② 通用岗名一刀切拦掉 —— 可化工企业的「工艺工程师」**确实是化工工艺**，
     学生学化工，这个岗就是他要找的。拦掉等于把真对口的企业推成「待核实」。

两种错的共同根因是：只看岗名，不看这家单位干什么。
所以这一层的做法是：**方向由主营业务推定，不由学生意向推定**。

  「工艺工程师」 + 主营「农药中间体、精细化工品」 → 化工方向 ✓
  「工艺工程师」 + 主营「汽车内饰件注塑」       → 机械/注塑方向 ✓
  「工艺工程师」 + 主营「跨境电商零售」         → 推不出方向，标 ask

方向一旦补上，比对就变成**方向对方向**：
学生填「化工工艺工程师」（化工）对「工艺工程师（化工）」→ 命中；
对「工艺工程师（机械）」→ 明确不同方向，不给 yes。

三条硬约束
----------
1. **纯确定性**：词表 + 字符串匹配，不调模型。企业库 145 家 × 1139 个岗位
   每次都能复算，且换词表不需要重跑模型。
2. **只在主营方向唯一时推定**：多元化集团（化工 + 地产 + 金融）推不出唯一方向，
   不硬猜，退回「要现场确认」。
3. **只对生产/技术类职能岗推定**：财务主管、人力资源专员不因为企业在化工厂
   就变成「化工财务」——那是职能，不是方向。见 `FUNC_TAKING`。
"""

