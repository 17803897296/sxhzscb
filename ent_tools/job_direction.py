def _strip(title):
    """去掉括号补充、英文/数字、尾部岗位词。返回「方向部分」。"""
    import job_profile as JP          # 延迟导入：job_profile 依赖本模块
    t = re.sub(r"[（(][^)）]*[)）]", "", str(title or "")).strip()
    t = re.sub(r"[A-Za-z0-9&+#\s]+", "", t)
    for tail in JP._T_BY_LEN:
        if t.endswith(tail) and len(t) > len(tail):
            return t[:-len(tail)]
    return t


def title_dir(title):
    """岗名**自己写着**的方向簇。没有则返回 ""。

        「化工工艺工程师」→ chem    「自动化工程师」→ auto
        「工艺工程师」    → ""      「设备维护工程师」→ ""
    """
    import job_profile as JP
    raw = re.sub(r"[（(][^)）]*[)）]", "", str(title or "")).strip()
    raw = re.sub(r"[A-Za-z0-9&+#\s]+", "", raw)
    if raw in JP._GENERIC_EXACT:
        return ""
    body = _strip(title)
    if body in JP._GENERIC_EXACT:
        return ""
    for w, c in _CL_BY_LEN:
        if w in body:
            return c
    # 「自控工程师」「仪表工程师」这类行业简称不在 DIR_STRONG 里，但确实是方向
    for w, c in (("自控", "auto"), ("仪控", "auto"), ("工控", "auto"),
                 ("仪表", "auto"), ("PLC", "auto")):
        if w.lower() in str(title or "").lower():
            return c
    return ""


def takes_func_dir(title):
    """这个岗的「方向」会不会跟着行业走（工艺/设备/质量/研发…）。"""
    t = str(title or "")
    return any(w in t for w in FUNC_TAKING)


def biz_dirs(text):
    """从主营业务描述里认出方向，按证据强度排序。

    返回 [(簇, 命中的词)]。两步都必要：

    · **长词优先且消费字符**：「新材料」不能再被拆成「材料」重复计数。
    · **按分数裁剪**：一段主营描述里常顺带提一句应用领域（「面向风力发电、
      气象环保、民航」），那不是这家在干的事。只留「命中数达到最高分一半」的簇，
      否则一家激光雷达公司会因为提到「环保」而被化工判定为环保方向。
    """
    s = str(text or "")
    if not s.strip():
        return []
    n, used, hits = len(s), [False] * len(s), []
    for w, c in _BIZ_BY_LEN:
        start = 0
        while True:
            i = s.find(w, start)
            if i < 0:
                break
            if not any(used[i:i + len(w)]):
                for k in range(i, i + len(w)):
                    used[k] = True
                hits.append((i, c, w))
            start = i + len(w)
    if not hits:
        return []
    hits.sort()
    score, first = {}, {}
    for i, c, _w in hits:
        score[c] = score.get(c, 0) + 1
        first.setdefault(c, i)
    # ① 先剔「只提了一次且不在前面」的噪声。
    #    实测出的典型：「上海妙文创意科技」主营里写了「施工」（做展陈），
    #    C++ 研发岗被推成土木方向；「银河航天」主营里写了「建筑」（厂房），
    #    卫星研发岗也被推成土木方向。方向和「提到」不是一回事。
    #
    #    阈值 2026-11-16 从 12 放宽到 25：12 是按「一句 30 字的主营」定的，
    #    而库里实际的主营描述多在 40~70 字，唯一的核心品类词常落在第 13~25 字——
    #    「猴姑饼干、猴姑米稀等食疗养胃食品」的「食品」在第 20 字、
    #    「加密货币矿机及AI算力芯片的研发与销售」的「芯片」在第 14 字。
    #    12 会把它们当噪声剔掉，结果是「有主营却推不出方向」。
    #    25 仍挡得住「主营 + 后半句应用领域」那种顺带一提。
    strong = {c for c in score
              if score[c] >= 2 or first[c] <= 25}
    out, seen = [], set()
    for _i, c, w in hits:
        if c not in strong or c in seen:
            continue
        seen.add(c)
        out.append((c, w))
    return out


# 「行业」字段里的粗分类标签。它们**不能**当作方向证据：
#   银河航天（做卫星）标签是「建筑」，江中食疗（做食疗食品）标签是「医药」，
#   两家唯一的业务文本就是这四个字。拿标签补方向，卫星研发会被推成土木、
#   食疗研发会被推成制药 —— 比不补更糟。
COARSE_TAGS = {"制造", "消费", "医药", "能源", "建筑", "it", "其他", "未知",
               "教育", "金融", "服务", "贸易", "零售", "物流", "地产", "文化",
               "农业", "交通", "医疗", "综合", ""}


def biz_text(*parts):
    """把行业标签、细分、主营描述拼成一段话给 biz_dirs 用。

    规则：**粗分类标签丢掉，其余全留**。
    · 丢掉的原因见 COARSE_TAGS —— 标签错得多，且信息量为零；
    · 描述排前面（长的在先是它的自然顺序，也便于人工核对依据词）。
    若一家企业只有标签没有描述，返回空串，等于「方向不可判定」，
    下游会退到 ask，而不是瞎猜一个。
    """
    ps = [str(p).strip() for p in parts if str(p or "").strip()]
    ps = [p for p in ps if p.lower() not in COARSE_TAGS]
    ps.sort(key=len, reverse=True)
    return "；".join(ps)


def resolve(title, biz=""):
    """完整判定：这个岗名指向哪些方向，方向从哪来。

    返回 {"dirs": [(簇, 依据词)], "cn": 首选方向中文, "src": "title"/"biz"/"", "why": ""}

    **dirs 是一组，不是单个**。这条是试出来的：一开始要求「主营方向唯一」才敢推定，
    结果海纳川（汽车零部件 + 汽车电子）、中建八局（房建 + 新能源新基建）全被判成
    「方向不唯一」，连带机械、土木学生也匹配不上 —— 主营业务里提一句「汽车电子」
    不等于主营变了。改成一组后，只要学生的方向落在这组里就算对得上；
    真正的多元化集团（化工 + 地产）两边都能对，那也是事实，不用挡。

    src 决定证据有多硬：
      title → 岗名自己写的方向；
      biz   → 从主营推定，报告里要标明「按主营推定」；
      ""    → 推不出方向，只能当「要现场确认」。
    """
    c = title_dir(title)
    if c:
        return {"dirs": [(c, "")], "cn": LABEL.get(c, c), "src": "title", "why": ""}
    if not takes_func_dir(title):
        return {"dirs": [], "cn": "", "src": "",
                "why": "这类岗做什么取决于装备，不取决于行业"}
    ds = biz_dirs(biz)
    if not ds:
        return {"dirs": [], "cn": "", "src": "",
                "why": "主营认不出方向"}
    # 位置靠前即主营核心（seg 在前、产品清单在后）
    return {"dirs": ds, "cn": LABEL.get(ds[0][0], ds[0][0]), "src": "biz",
            "why": "依据「%s」" % ds[0][1]}


def pick(dirs, want, title=""):
    """从一组可能方向里挑出与学生方向相容的那个；挑不到返回 None。

    want 是学生方向集（空集 = 学生没有方向偏好，此时取首选方向）。
    title 用于按职能判断交叉可换（见 FUNC_CROSS）。
    """
    if not dirs:
        return None
    if not want:
        return dirs[0]
    # 先找同名方向，再找相邻方向 —— 否则学生会看到「制药方向」这种沾边标签
    # （多恩做的是印染助剂，主营里也提到医药，精确命中化工才是对的）
    for c, kw in dirs:
        if c in want:
            return (c, kw)
    for c, kw in dirs:
        if any(compatible(s, c, title) for s in want):
            return (c, kw)
    return None


def compatible(a, b, title=""):
    """两个方向簇能不能算同一方向（含相邻可换，以及按职能成立的方向交叉）。

    title 给出岗位名时，额外检查两件事：
      · FUNC_CROSS：同样是 chem × elec2，「刻蚀工艺工程师」算通（工艺岗收化工），
        「器件研发工程师」不算通；
      · FUNC_NOCROSS：相邻方向里个别岗名**不能**换，家具厂的「结构工程师」是
        产品结构（机械），不是建筑结构（土木），尽管 mech~civil 整体可换。
    同簇永远相容，不受这两张表影响。
    """
    if not a or not b:
        return False
    if a == b:
        return True
    if title:
        banned = FUNC_NOCROSS.get((a, b)) or FUNC_NOCROSS.get((b, a))
        if banned and any(w in str(title) for w in banned):
            return False
    if (a, b) in COMPAT or (b, a) in COMPAT:
        return True
    if title:
        key = (a, b) if (a, b) in FUNC_CROSS else (
            (b, a) if (b, a) in FUNC_CROSS else None)
        if key and any(w in str(title) for w in FUNC_CROSS[key]):
            return True
    return False
