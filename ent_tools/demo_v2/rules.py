# 城市 → 命中的类别列表（能级互斥取其一 + 特质可叠加）
def city_categories(city):
    if not city or city in ("未知", ""):
        return []
    cats = []
    if city in CITY_FIRST:
        cats.append("一线")
    elif city in CITY_NEW1:
        cats.append("新一线")
    elif city in CITY_CAPITAL:
        cats.append("其他省会")
    else:
        cats.append("其他")
    if city in CITY_ECON:
        cats.append("经济发达")
    if city in CITY_TRANSIT:
        cats.append("交通发达")
    if city in CITY_ECO:
        cats.append("生态友好")
    return cats

# 排名 → 得分：第 1 名=1.0，最后一名=0.4，线性递减（n 为该类总数）
def rank_value(rank, n):
    if n <= 1:
        return 1.0
    return round(1.0 - (rank - 1) / (n - 1) * 0.6, 3)

